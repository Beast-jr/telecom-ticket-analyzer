import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT_PATH = path.join(ROOT, "docs/eval-comparison.md");

// The subset of evaluate.ts's EvalResult that the comparison needs.
interface EvalResult {
  id: string;
  category: string;
  subtopic: string;
  description: string;
  categoryHit5: boolean;
  top1Category: boolean;
  subtopicHit5: boolean;
  topSimilarity: number;
  top1Suitability: number;
  solutions: { rank: number; title: string }[];
  judge: { top1Score: number; bestOf3Score: number; top1Useful: number; bestOf3Useful: number; distinct: boolean; reason: string };
}

const { values } = parseArgs({ options: { a: { type: "string", default: "v1" }, b: { type: "string", default: "v2" } } });
const tagA = values.a;
const tagB = values.b;

function load(tag: string): EvalResult[] {
  const p = path.join(ROOT, `data/eval/results-${tag}.json`);
  if (!existsSync(p)) {
    console.error(`Missing ${p}. Run "npm run eval -- --tag ${tag}" first.`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(p, "utf8")) as EvalResult[];
}

const a = load(tagA);
const b = load(tagB);

const avg = (xs: number[]) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : NaN);
const rate = (rs: EvalResult[], f: (r: EvalResult) => boolean) => (rs.length ? (100 * rs.filter(f).length) / rs.length : NaN);

// [label, compute, unit]: "%" metrics show percentage-point deltas.
const METRICS: [string, (rs: EvalResult[]) => number, "%" | "score" | "n"][] = [
  ["n", (rs) => rs.length, "n"],
  ["categoryHit@5", (rs) => rate(rs, (r) => r.categoryHit5), "%"],
  ["top1Category", (rs) => rate(rs, (r) => r.top1Category), "%"],
  ["subtopicHit@5", (rs) => rate(rs, (r) => r.subtopicHit5), "%"],
  ["avg top1Score (match)", (rs) => avg(rs.map((r) => r.judge.top1Score)), "score"],
  ["avg bestOf3Score (match)", (rs) => avg(rs.map((r) => r.judge.bestOf3Score)), "score"],
  ["avg top1Useful", (rs) => avg(rs.map((r) => r.judge.top1Useful)), "score"],
  ["avg bestOf3Useful", (rs) => avg(rs.map((r) => r.judge.bestOf3Useful)), "score"],
  ["distinct", (rs) => rate(rs, (r) => r.judge.distinct), "%"],
  ["avg #1 suitability", (rs) => avg(rs.map((r) => r.top1Suitability)), "score"],
];

function fmt(x: number, unit: string): string {
  if (Number.isNaN(x)) return "-";
  if (unit === "%") return `${Math.round(x)}%`;
  if (unit === "n") return String(x);
  return x.toFixed(2);
}

function delta(x: number, y: number, unit: string): string {
  if (Number.isNaN(x) || Number.isNaN(y)) return "-";
  const d = y - x;
  const shown = unit === "%" ? `${Math.round(d)} pp` : unit === "n" ? String(d) : d.toFixed(2);
  return d > 0 ? `+${shown}` : shown;
}

const table = (headers: string[], rows: (string | number)[][]) =>
  [`| ${headers.join(" | ")} |`, `| ${headers.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

// Summaries over each full file, and over the tickets both runs share (fair comparison).
const bIds = new Set(b.map((r) => r.id));
const aById = new Map(a.map((r) => [r.id, r]));
const commonA = a.filter((r) => bIds.has(r.id));
const commonB = b.filter((r) => aById.has(r.id));

const summaryRows = (ra: EvalResult[], rb: EvalResult[]) =>
  METRICS.map(([label, f, unit]) => [label, fmt(f(ra), unit), fmt(f(rb), unit), delta(f(ra), f(rb), unit)]);

const changes = commonB
  .map((rb) => ({ rb, ra: aById.get(rb.id)! }))
  .map(({ ra, rb }) => ({ ra, rb, d: rb.judge.top1Useful - ra.judge.top1Useful }))
  .filter((c) => c.d !== 0)
  .sort((x, y) => y.d - x.d);

const changeRows = (list: typeof changes) =>
  list.map(({ ra, rb, d }) => [
    rb.id,
    `${rb.category} › ${rb.subtopic}`,
    `${ra.judge.top1Useful} → ${rb.judge.top1Useful} (${d > 0 ? "+" : ""}${d})`,
    `${ra.judge.top1Score} → ${rb.judge.top1Score}`,
    ra.solutions[0]?.title ?? "-",
    rb.solutions[0]?.title ?? "-",
  ]);
const changeHeaders = ["Ticket", "Category › subtopic", "#1 useful", "#1 match", `#1 in ${tagA}`, `#1 in ${tagB}`];

const up = changes.filter((c) => c.d > 0);
const down = changes.filter((c) => c.d < 0);
const same = commonB.length - changes.length;

const md = `# Eval comparison: ${tagA} vs ${tagB}

Generated by \`backend/scripts/compare-eval.ts\` from \`data/eval/results-${tagA}.json\` (${a.length} tickets) and \`data/eval/results-${tagB}.json\` (${b.length} tickets).

## Summary (tickets in both runs: ${commonB.length})

${table(["Metric", tagA, tagB, "Δ"], summaryRows(commonA, commonB))}
${
  a.length !== commonA.length || b.length !== commonB.length
    ? `
## Summary (each run's full results)

${table(["Metric", tagA, tagB, "Δ"], summaryRows(a, b))}
`
    : ""
}
## #1 usefulness by ticket

Of ${commonB.length} shared tickets, #1 useful went **up for ${up.length}**, **down for ${down.length}**, and stayed the same for ${same}.

### Went up

${up.length ? table(changeHeaders, changeRows(up)) : "_None._"}

### Went down

${down.length ? table(changeHeaders, changeRows(down)) : "_None._"}

## Notes

- Retrieval is identical between runs (same store, same holdout), so retrieval metrics should not change. The solution LLM runs at temperature 0.2 and LLM output isn't fully repeatable even at the judge's temperature 0, so a ±1 change on a single ticket can be noise.
- Δ for percentages is in percentage points (pp).
`;

mkdirSync(path.dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, md, "utf8");
console.log(`Compared ${tagA} (${a.length}) vs ${tagB} (${b.length}); ${commonB.length} shared tickets. Up ${up.length}, down ${down.length}.`);
console.log(`Wrote ${OUT_PATH}`);
